"""Generates src/tables.mjs: single-byte PDF encodings as code -> Unicode, and a
trimmed Adobe Glyph List (glyph name -> Unicode) for /Differences arrays."""
import json
import os

from fontTools.agl import AGL2UV
from fontTools.encodings.StandardEncoding import StandardEncoding

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "tables.mjs")


def from_codec(codec):
    table = []
    for code in range(256):
        try:
            ch = bytes([code]).decode(codec)
            table.append(ord(ch) if code >= 32 else 0)
        except UnicodeDecodeError:
            table.append(0)
    return table


win = from_codec("cp1252")
# PDF 1.7 Annex D: WinAnsi 0x7F..0xFF undefined slots render as bullet, but
# they are not real characters; keep them 0 so they are never chosen.
mac = from_codec("mac_roman")
std = [AGL2UV.get(n, 0) if n != ".notdef" else 0 for n in StandardEncoding]


def keep(uv):
    return (uv < 0x0250 or 0x0370 <= uv < 0x0530 or 0x1E00 <= uv < 0x1F00
            or 0x2000 <= uv < 0x2200 or 0xFB00 <= uv < 0xFB07)


agl = {name: uv for name, uv in AGL2UV.items() if keep(uv)}
with open(OUT, "w", encoding="utf-8") as f:
    f.write("// Generated by tools/gen_tables.py. Do not edit.\n")
    f.write("export const WinAnsiEncoding = %s;\n" % json.dumps(win))
    f.write("export const MacRomanEncoding = %s;\n" % json.dumps(mac))
    f.write("export const StandardEncoding = %s;\n" % json.dumps(std))
    f.write("export const AGL = %s;\n" % json.dumps(agl, separators=(",", ":")))
print("wrote", OUT, os.path.getsize(OUT), "bytes,", len(agl), "glyph names")
